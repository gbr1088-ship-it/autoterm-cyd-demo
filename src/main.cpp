// ---------------------------------------------------------------- temperature probe
// Non-blocking: start a conversion, collect the result on the next call.
// If the probe is missing or unplugged the demo falls back to the simulation.
void pollSensor() {
  static uint32_t lastPoll = 0, lastSearch = 0;
  static uint8_t fails = 0;
  uint32_t now = millis();

  if (!sensorOk) {
    if (now - lastSearch < 5000 && lastSearch) return;
    lastSearch = now;
    sensors.begin();
    if (sensors.getDeviceCount() == 0) {
      // a presence pulse with no device found usually means a wiring fault on the data line
      Serial.printf("[sensor] no DS18B20 on IO%d (bus presence pulse: %s)\n", TEMP_SENSOR_PIN,
                    oneWire.reset() ? "yes" : "no");
      return;
    }
    sensors.setResolution(11);  // 0.125 C, ~375 ms per conversion
    sensors.setWaitForConversion(true);
    sensors.requestTemperatures();  // one blocking read so the gauge starts with a real value
    float t = sensors.getTempCByIndex(0);
    if (t == DEVICE_DISCONNECTED_C) {
      Serial.println("[sensor] DS18B20 found but not answering - check the 4.7k resistor");
      return;
    }
    cabinTemp = t;
    sensors.setWaitForConversion(false);
    sensors.requestTemperatures();
    sensorOk = true;
    fails = 0;
    lastPoll = now;
    Serial.printf("[sensor] DS18B20 found, %.1f C\n", t);
    return;
  }

  if (now - lastPoll < 1000) return;
  lastPoll = now;
  float t = sensors.getTempCByIndex(0);
  if (t == DEVICE_DISCONNECTED_C || t < -55 || t > 125) {
    if (++fails >= 3) {
      sensorOk = false;
      Serial.println("[sensor] lost, using simulation");
    }
  } else {
    fails = 0;
    cabinTemp = t;
  }
  sensors.requestTemperatures();
}

// ---------------------------------------------------------------- touch
bool readTouch(int &x, int &y) {
  if (!ts.tirqTouched() || !ts.touched()) return false;
  TS_Point p = ts.getPoint();
  if (p.z < 300) return false;
  x = constrain(map(p.x, TOUCH_X_MIN, TOUCH_X_MAX, 0, 320), 0, 319);
  y = constrain(map(p.y, TOUCH_Y_MIN, TOUCH_Y_MAX, 0, 240), 0, 239);
  Serial.printf("touch raw %d,%d z=%d -> %d,%d\n", p.x, p.y, p.z, x, y);
  return true;
}

void onPress(int x, int y) {
  if (page != PAGE_HOME && hit(btnHome, x, y)) { showPage(PAGE_HOME); return; }
  switch (page) {
    case PAGE_HOME:
      if (hit(btnHeatTile, x, y)) showPage(PAGE_HEATER);
      if (hit(btnUtilTile, x, y)) showPage(PAGE_UTIL);
      break;
    case PAGE_HEATER:
      if (hit(btnPower, x, y)) onPowerPressed();
      for (int i = 0; i < 3; i++)
        if (hit(btnMode[i], x, y)) onModePressed((Mode)i);
      if (hit(btnMinus, x, y)) { drawAdjButton(btnMinus, false, true); onAdjust(-1); }
      if (hit(btnPlus, x, y))  { drawAdjButton(btnPlus, true, true); onAdjust(+1); }
      break;
    case PAGE_UTIL:
      for (int i = 0; i < 3; i++)
        if (hit(btnToggle[i], x, y)) onToggle(i);
      if (hit(btnWinUp, x, y)) setWinch(WIN_UP);
      if (hit(btnWinDown, x, y)) setWinch(WIN_DOWN);
      break;
  }
}

void handleTouch() {
  static bool wasHeld = false;
  static uint32_t downAt = 0, lastRepeat = 0, lastSeen = 0;
  int x, y;
  bool down = readTouch(x, y);
  uint32_t now = millis();
  if (down) lastSeen = now;
  // the touch reading drops out for a moment now and then while a finger is
  // held; treat gaps under 150 ms as still held
  bool held = down || (wasHeld && now - lastSeen < 150);

  if (down && !wasHeld) {
    downAt = lastRepeat = now;
    onPress(x, y);
  } else if (down && page == PAGE_HEATER && now - downAt > 500 && now - lastRepeat > 150) {
    // hold +/- to auto-repeat
    lastRepeat = now;
    if (hit(btnMinus, x, y)) onAdjust(-1);
    if (hit(btnPlus, x, y)) onAdjust(+1);
  } else if (down && page == PAGE_UTIL && winch != WIN_STOP) {
    // sliding off the windlass button stops it
    if (!hit(winch == WIN_UP ? btnWinUp : btnWinDown, x, y)) setWinch(WIN_STOP);
  } else if (!held && wasHeld) {
    if (page == PAGE_HEATER) {
      drawAdjButton(btnMinus, false, false);
      drawAdjButton(btnPlus, true, false);
    }
    setWinch(WIN_STOP);
  }
  wasHeld = held;
}

// ---------------------------------------------------------------- arduino
void setup() {
  Serial.begin(115200);
  pinMode(LED_R, OUTPUT);
  pinMode(LED_G, OUTPUT);
  pinMode(LED_B, OUTPUT);
  setLed(false, false, false);

  touchSpi.begin(XPT2046_CLK, XPT2046_MISO, XPT2046_MOSI, XPT2046_CS);
  ts.begin(touchSpi);
  ts.setRotation(1);

  tft.init();
  tft.setRotation(1);  // landscape, USB on the right; use 3 to flip
  tft.setSwapBytes(true);
  ledcSetup(BL_CHANNEL, 5000, 8);
  ledcAttachPin(TFT_BL, BL_CHANNEL);
  backlight(0);

  // sprite sizes keep them inside the gauge ring so they never erase the arc
  anim.createSprite(40, 34);
  tempSpr.createSprite(122, 44);
  setSpr.createSprite(112, 22);
  infoSpr.createSprite(120, 18);
  winSpr.createSprite(116, 72);

  pollSensor();  // look for the DS18B20 before the first frame

  splash();
  showPage(PAGE_HOME);
  fadeBacklight(0, 255, 300);
  stateSince = millis();
}

void loop() {
  static uint32_t lastSim = millis(), lastDraw = 0, lastAnim = 0;
  static int lastChain = -1;
  uint32_t now = millis();

  handleTouch();
  pollSensor();

  if (now - lastSim >= 50) {
    float dt = (now - lastSim) / 1000.0f;
    simulate(dt);
    simulateWinch(dt);
    lastSim = now;
  }
  if (page == PAGE_HEATER && now - lastAnim >= 120) {
    animTick++;
    drawAnimation();
    lastAnim = now;
  }
  if (page == PAGE_UTIL && lroundf(chainOut * 10) != lastChain) {
    lastChain = lroundf(chainOut * 10);
    drawWinchStatus();
  }
  if (now - lastDraw >= 250) {
    if (page == PAGE_HEATER) drawDynamic();
    else if (page == PAGE_HOME) drawHomeStatus();
    if (page != PAGE_HEATER) drawVoltage();
    lastDraw = now;
  }
}
