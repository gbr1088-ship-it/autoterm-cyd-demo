void drawGauge() {
  float f = (cabinTemp - G_MIN_T) / (G_MAX_T - G_MIN_T);
  f = constrain(f, 0.0f, 1.0f);
  int endA = G_START + f * (G_END - G_START);

  // filled part as short segments so the colour sweeps along the arc
  for (int a = G_START; a < endA; a += 10) {
    int b = min(a + 10, endA);
    float mid = (float)(a - G_START) / (G_END - G_START);
    tft.drawArc(GX, GY, GR, GIR, a, b, heatColor(mid), C_BG, true);
  }
  if (endA < G_END) tft.drawArc(GX, GY, GR, GIR, endA, G_END, C_TRACK, C_BG, true);

  // rounded caps
  float x, y;
  const float mid = (GR + GIR) / 2.0f, capR = (GR - GIR) / 2.0f;
  arcPoint(G_START, mid, x, y);
  tft.fillSmoothCircle(x, y, capR, f > 0 ? heatColor(0) : C_TRACK, C_BG);
  arcPoint(G_END, mid, x, y);
  tft.fillSmoothCircle(x, y, capR, f >= 1 ? heatColor(1) : C_TRACK, C_BG);

  // setpoint marker
  if (mode == MODE_TEMP) {
    float sf = (setTemp - G_MIN_T) / (G_MAX_T - G_MIN_T);
    arcPoint(G_START + sf * (G_END - G_START), mid, x, y);
    tft.fillSmoothCircle(x, y, capR - 1, C_TEXT, C_BG);
    tft.fillSmoothCircle(x, y, capR - 4, C_ORANGE, C_TEXT);
  }
}

