// Autoterm diesel heater controller - touchscreen DEMO
// Target: ESP32-2432S028 ("Cheap Yellow Display"), 320x240 ILI9341 + XPT2046
//
// The heater itself is simulated. Every place where a real heater would be
// commanded is marked with "HEATER LINK" so a UART driver can be dropped in later.
//
// Pages: HOME (pick Heating or Utilities), HEATER, UTILITIES. The utilities
// relays (lights, pumps, windlass) are simulated too; the places where a
// wireless relay box would be commanded are marked "RELAY LINK".
// After a minute without a touch a screensaver shows a logo with the date
// and time; a tap goes back to the page you were on.
// A settings page (from the home page) sets the language (English, French,
// Spanish), the screen brightness and whether the screensaver is used; the
// choices are kept in flash so they survive a power cut.
// Link: a second board running the same firmware can be set to REMOTE. It
// mirrors the MAIN screen over ESP-NOW and sends its button presses back; the
// main screen stays the only one that controls the heater and relays.
// Updates: Settings > System sets up WiFi (from a phone) and checks a secret
// GitHub Gist for newer firmware, which it downloads, verifies and installs.
// Phone: the PHONE button on the home page opens the screen's own WiFi
// network (password protected) and serves a phone app from web/app.html.
// The phone does what the screen's buttons do, except run the windlass.

