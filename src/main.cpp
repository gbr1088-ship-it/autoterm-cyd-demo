// WiFi is only switched on to set it up or to check for / download an update.
// While it's connected the radio follows the boat network's channel, so the
// screen link and the phone network drop for a moment and recover afterwards.
const char TIMEZONE[] = "GMT0BST,M3.5.0/1,M10.5.0";  // UK time, with summer time

