// GET a file from the update Gist over HTTPS, checking GitHub's certificate
bool httpsGet(const char *file, WiFiClientSecure &client, HTTPClient &http) {
  char url[200];
  snprintf(url, sizeof url, "%s%s", UPDATE_BASE_URL, file);
  client.setCACert(GITHUB_ROOTS);
  http.setFollowRedirects(HTTPC_STRICT_FOLLOW_REDIRECTS);
  http.setTimeout(15000);
  if (!http.begin(client, url)) return false;
  int code = http.GET();
  if (code == HTTP_CODE_OK) return true;
  Serial.printf("[update] %s: HTTP %d\n", file, code);
  http.end();
  return false;
}

// version.txt in the Gist, written by tools/publish_update.ps1:
//   version=4
//   kolex=<sha256 hex> <size>
//   beneteau=<sha256 hex> <size>
void parseVersionFile(const String &body) {
  int ver = 0, pos = 0;
  updSize = 0;
  updSha[0] = 0;
  String mine = String(FW_VARIANT) + "=";
  while (pos < (int)body.length()) {
    int nl = body.indexOf('\n', pos);
    if (nl < 0) nl = body.length();
    String line = body.substring(pos, nl);
    line.trim();
    pos = nl + 1;
    if (line.startsWith("version=")) ver = line.substring(8).toInt();
    else if (line.startsWith(mine)) {
      String v = line.substring(mine.length());
      if (v.indexOf(' ') != 64) continue;
      strncpy(updSha, v.c_str(), 64);
      updSha[64] = 0;
      updSize = v.substring(65).toInt();
    }
  }
  if (ver <= 0 || !updSize) return;
  updVersion = ver;
  updStatus = ver > FW_VERSION ? UPD_AVAILABLE : UPD_CURRENT;
}

void checkForUpdate() {
  if (!strlen(UPDATE_BASE_URL)) {
    Serial.println("[update] no update address set (UPDATE_BASE_URL in platformio.ini)");
    updStatus = UPD_FAILED;
    return;
  }
  if (!wm.getWiFiIsSaved()) {
    updStatus = UPD_NO_WIFI;
    return;
  }
  updStatus = UPD_CHECKING;
  drawUpdateRow();
  if (!wifiConnect()) {
    updStatus = UPD_NO_CONN;
    wifiOff();
    return;
  }
  updStatus = UPD_FAILED;
  WiFiClientSecure client;
  HTTPClient http;
  if (httpsGet("version.txt", client, http)) {
    parseVersionFile(http.getString());
    http.end();
  }
  wifiOff();
  Serial.printf("[update] running %d, available %d\n", FW_VERSION, updStatus == UPD_FAILED ? 0 : updVersion);
}

