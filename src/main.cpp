// redraw the parts that depend on live values, only when they change
void drawDynamic(bool force = false) {
  static int lastTemp = INT32_MIN, lastSet = -1, lastRpm = -1, lastOut = -1, lastVolt = -1;
  static Mode lastMode = MODE_TEMP;
  static HeaterState lastState = ST_OFF;
  static bool lastSensor = false;
  int t = lroundf(cabinTemp * 10);
  int s = mode == MODE_TEMP ? setTemp : mode == MODE_POWER ? powerLevel : fanLevel;

  if (force || t != lastTemp || s != lastSet || mode != lastMode) {
    drawGauge();
    drawTemperature();
    drawSetLine();
  }
  if (force || (int)fanRpm / 10 != lastRpm || (int)(output * 100) != lastOut ||
      state != lastState || sensorOk != lastSensor) drawInfoLine();
  if (force || lroundf(voltage * 10) != lastVolt) drawVoltage();

  lastTemp = t; lastSet = s; lastMode = mode; lastState = state; lastSensor = sensorOk;
  lastRpm = (int)fanRpm / 10; lastOut = (int)(output * 100); lastVolt = lroundf(voltage * 10);
}

void drawAnimation() {
  const int cx = anim.width() / 2;
  float phase = ((animTick * 37) % 10) / 9.0f;  // irregular flicker
  anim.fillSprite(C_BG);
  if (state == ST_RUNNING || (state == ST_STARTING && millis() - stateSince > START_MS / 2)) {
    drawFlame(anim, cx, 32, 10, phase, C_BG);
  } else if (state == ST_VENTING || state == ST_COOLDOWN || state == ST_STARTING) {
    drawFan(anim, cx, 17, 14, animTick * 0.5f, C_BLUE, C_BG);
  } else {
    anim.setTextDatum(MC_DATUM);
    anim.setTextColor(C_DIM, C_BG);
    anim.drawString("CABIN", cx, 20, 2);
  }
  anim.pushSprite(GX - anim.width() / 2, 56);
}

// ---------------------------------------------------------------- heater control
void setState(HeaterState s) {
  state = s;
  stateSince = millis();
  if (page == PAGE_HEATER) {
    drawPowerButton();
    drawStatePill();
  }
  Serial.printf("[heater] -> %s\n", STATE_TEXT[s]);
}

void onPowerPressed() {
  switch (state) {
    case ST_OFF:
      // HEATER LINK: send start command (mode + setpoint) here
      setState(mode == MODE_VENT ? ST_VENTING : ST_STARTING);
      break;
    case ST_STARTING:
    case ST_RUNNING:
      // HEATER LINK: send stop command
      setState(ST_COOLDOWN);
      break;
    case ST_VENTING:
      setState(ST_OFF);
      break;
    case ST_COOLDOWN:
      break;  // must finish purge first
  }
}

void onModePressed(Mode m) {
  if (m == mode) return;
  // a running burner can switch between TEMP/POWER; VENT needs a stop first
  bool burning = state == ST_STARTING || state == ST_RUNNING;
  if ((burning && m == MODE_VENT) || (state == ST_VENTING && m != MODE_VENT)) return;
  mode = m;
  drawModeSelector();
  drawDynamic();
  // HEATER LINK: send new mode/setpoint
}

void onAdjust(int d) {
  if (mode == MODE_TEMP) setTemp = constrain(setTemp + d, 1, 30);
  else if (mode == MODE_POWER) powerLevel = constrain(powerLevel + d, 0, 9);
  else fanLevel = constrain(fanLevel + d, 1, 9);
  // HEATER LINK: send new setpoint
  drawDynamic();
}

// Simple thermal model so the demo looks alive
void simulate(float dt) {
  uint32_t t = millis() - stateSince;
  float targetOut = 0, targetRpm = 0;
  voltage = 12.7f;

  switch (state) {
    case ST_OFF:
      break;
    case ST_STARTING:
      voltage = 12.1f;  // glow plug load
      targetRpm = 1500;
      targetOut = t > START_MS / 2 ? 0.2f : 0.0f;
      if (t > START_MS) setState(ST_RUNNING);
      break;
    case ST_RUNNING:
      voltage = 12.5f;
      if (mode == MODE_TEMP) targetOut = constrain(0.15f + (setTemp - cabinTemp) * 0.25f, 0.1f, 1.0f);
      else targetOut = 0.1f + powerLevel * 0.1f;
      targetRpm = 1200 + targetOut * 3300;
      break;
    case ST_VENTING:
      targetRpm = 600 + fanLevel * 350;
      break;
    case ST_COOLDOWN:
      targetRpm = 3000;
      if (t > COOLDOWN_MS) setState(ST_OFF);
      break;
  }

  output += (targetOut - output) * min(1.0f, dt * 0.8f);
  fanRpm += (targetRpm - fanRpm) * min(1.0f, dt * 1.5f);
  // 2kW into a small cabin: ~1 C per 10 s at full power; loses heat to ambient
  if (!sensorOk) cabinTemp += (output * 0.12f - (cabinTemp - AMBIENT) * 0.004f) * dt;

  setLed(state == ST_RUNNING || state == ST_STARTING, false, state == ST_VENTING || state == ST_COOLDOWN);
}

