// ---------------------------------------------------------------- helpers
bool hit(const Button &b, int x, int y) {
  return x >= b.x && x < b.x + b.w && y >= b.y && y < b.y + b.h;
}

void setLed(bool r, bool g, bool b) {
  digitalWrite(LED_R, !r);
  digitalWrite(LED_G, !g);
  digitalWrite(LED_B, !b);
}

void backlight(uint8_t level) { ledcWrite(BL_CHANNEL, level); }

void fadeBacklight(int from, int to, int ms) {
  int steps = 32;
  for (int i = 0; i <= steps; i++) {
    backlight(from + (to - from) * i / steps);
    delay(ms / steps);
  }
}

// cold blue -> orange -> red along the gauge
uint16_t heatColor(float f) {
  f = constrain(f, 0.0f, 1.0f);
  if (f < 0.5f) return tft.alphaBlend(f * 2 * 255, C_ORANGE, C_BLUE);
  return tft.alphaBlend((f - 0.5f) * 2 * 255, C_RED, C_ORANGE);
}

void arcPoint(float angle, float r, float &x, float &y) {
  float a = angle * DEG_TO_RAD;
  x = GX - sinf(a) * r;
  y = GY + cosf(a) * r;
}

// small "o" for the degree sign - the free fonts don't include one
void drawDegree(TFT_eSPI &g, int x, int y, int r, uint16_t col, uint16_t bg) {
  g.drawSmoothCircle(x, y, r, col, bg);
  g.drawSmoothCircle(x, y, r - 1, col, bg);
}

// Teardrop flame with a soft glow; flicker 0..1 changes its height
void drawFlame(TFT_eSPI &g, int cx, int by, int size, float flicker, uint16_t bg) {
  int h = size * (1.6f + 0.25f * flicker);
  g.fillSmoothCircle(cx, by - size / 2, size + 2, g.alphaBlend(40, C_ORANGE, bg), bg);
  g.fillSmoothCircle(cx, by - size / 2, size / 2 + 2, C_RED, bg);
  g.fillTriangle(cx - size / 2 - 2, by - size / 2, cx + size / 2 + 2, by - size / 2, cx + (flicker - 0.5f) * 4, by - h, C_RED);
  g.fillSmoothCircle(cx, by - size / 2 + 1, size / 3, C_ORANGE, C_RED);
  g.fillTriangle(cx - size / 3, by - size / 2 + 1, cx + size / 3, by - size / 2 + 1, cx - (flicker - 0.5f) * 3, by - h * 0.7f, C_ORANGE);
  g.fillSmoothCircle(cx, by - size / 2 + 3, size / 6, C_YELLOW, C_ORANGE);
}

void drawFan(TFT_eSPI &g, int cx, int cy, int r, float angle, uint16_t col, uint16_t bg) {
  g.drawSmoothCircle(cx, cy, r, C_RAISED, bg);
  for (int i = 0; i < 3; i++) {
    float a = angle + i * 2.0944f;
    g.drawWedgeLine(cx, cy, cx + cosf(a) * (r - 4), cy + sinf(a) * (r - 4), 2, 6, col, bg);
  }
  g.fillSmoothCircle(cx, cy, 3, C_TEXT, col);
}

