// Redrawn once a minute: the time on the left and the date on the right,
// over the top of the current image.
void drawSaverClock(bool force = false) {
  static int lastMin = -1;
  time_t now = time(nullptr);
  struct tm t;
  localtime_r(&now, &t);
  int m = t.tm_hour * 60 + t.tm_min;
  if (!force && m == lastMin) return;
  lastMin = m;

  const SaverImage &img = SAVER_IMAGES[saverIndex];
  for (int y = 0; y < SAVER_BAND_H; y++) {
    uint8_t a = img.shade ? 180 - y * 160 / SAVER_BAND_H : 0;  // fades out downwards
    for (int x = 0; x < 320; x++) {
      uint16_t c = img.bitmap ? pgm_read_word(&img.bitmap[y * 320 + x]) : C_BG;
      saverSpr.drawPixel(x, y, a ? tft.alphaBlend(a, TFT_BLACK, c) : c);
    }
  }

  char buf[32];
  strftime(buf, sizeof buf, "%H:%M", &t);
  saverSpr.setFreeFont(&FreeSansBold24pt7b);
  saverSpr.setTextDatum(ML_DATUM);
  saverSpr.setTextColor(img.light ? C_BG : C_TEXT);
  saverSpr.drawString(buf, 12, 26);
  saverSpr.setTextDatum(MR_DATUM);
  saverSpr.setFreeFont(&FreeSansBold9pt7b);
  saverSpr.drawString(DAY_NAME[lang][t.tm_wday], 308, 16);
  const char *month = MONTH_NAME[lang][t.tm_mon];
  if (lang == LANG_ES) snprintf(buf, sizeof buf, "%d de %s de %d", t.tm_mday, month, t.tm_year + 1900);
  else snprintf(buf, sizeof buf, "%d %s %d", t.tm_mday, month, t.tm_year + 1900);
  saverSpr.setTextColor(img.light ? rgb(70, 80, 95) : rgb(205, 210, 218));
  saverSpr.drawString(buf, 308, 38, 2);
  saverSpr.pushSprite(0, 0);
}

