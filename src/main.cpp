// Hold-to-run: the windlass only moves while a finger is on UP or DOWN.
// Main screen only: a remote shows the windlass but can't run it.
void setWinch(Winch w) {
  if (w == winch || isRemote()) return;
  // RELAY LINK: the relay box never energises UP and DOWN together. While
  // running, send a keep-alive every 100 ms; the box stops the windlass by
  // itself if they stop arriving (finger lifted, crash or radio dropout).
  Winch old = winch;
  winch = w;
  Serial.printf("[relay] windlass -> %s\n", w == WIN_UP ? "UP" : w == WIN_DOWN ? "DOWN" : "STOP");
  drawWinchChange(old);
}

void simulateWinch(float dt) {
  if (winch == WIN_UP) {
    chainOut -= CHAIN_RATE * dt;
    if (chainOut <= 0) { chainOut = 0; setWinch(WIN_STOP); }  // anchor home: stop
  } else if (winch == WIN_DOWN) {
    chainOut += CHAIN_RATE * dt;
    if (chainOut >= CHAIN_MAX) { chainOut = CHAIN_MAX; setWinch(WIN_STOP); }
  }
}

// ---------------------------------------------------------------- screensaver
// The CYD has no clock chip and the demo has no internet time, so the clock
// starts at the firmware build time and resets to it on every power-up.
void setClockFromBuild() {
  static const char MONTHS[] = "JanFebMarAprMayJunJulAugSepOctNovDec";
  char mon[4];
  int d, y, hh, mm, ss;
  sscanf(__DATE__, "%3s %d %d", mon, &d, &y);
  sscanf(__TIME__, "%d:%d:%d", &hh, &mm, &ss);
  struct tm t = {};
  t.tm_year = y - 1900;
  t.tm_mon = (strstr(MONTHS, mon) - MONTHS) / 3;
  t.tm_mday = d;
  t.tm_hour = hh;
  t.tm_min = mm;
  t.tm_sec = ss;
  timeval tv = {mktime(&t), 0};
  settimeofday(&tv, nullptr);
}

// 320x240 screensaver images. A light image gets dark clock text; a dark one
