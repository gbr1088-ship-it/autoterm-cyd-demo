"""Packs the phone app (web/app.html + web/icon.png) into src/webapp.h.

The screen serves this page to phones that join its WiFi. Run it after
changing anything in web/:

    python tools/web2header.py

web/app.html holds only the page's own content (title, style, markup,
script) so it can also be opened straight from disk as a demo. This script
wraps it in a full document with the phone "add to home screen" settings,
gzips it and writes it out as C arrays.
"""
import gzip
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
APP = ROOT / "web" / "app.html"
ICON = ROOT / "web" / "icon.png"
OUT = ROOT / "src" / "webapp.h"

HEAD = """<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">
<meta name="apple-mobile-web-app-capable" content="yes">
<meta name="mobile-web-app-capable" content="yes">
<meta name="apple-mobile-web-app-status-bar-style" content="black-translucent">
<meta name="apple-mobile-web-app-title" content="Cabin">
<meta name="theme-color" content="#0a0d12">
<link rel="icon" href="/icon.png">
<link rel="apple-touch-icon" href="/icon.png">
<link rel="manifest" href="/manifest.json">
<style>:root{padding-top:env(safe-area-inset-top,0px);padding-bottom:env(safe-area-inset-bottom,0px)}</style>
"""

MANIFEST = {
    "name": "Cabin Control",
    "short_name": "Cabin",
    "start_url": "/",
    "display": "standalone",
    "background_color": "#0a0d12",
    "theme_color": "#0a0d12",
    "icons": [{"src": "/icon.png", "sizes": "180x180", "type": "image/png"}],
}


def c_array(name, data):
    rows = [", ".join(f"0x{b:02x}" for b in data[i:i + 20]) for i in range(0, len(data), 20)]
    body = ",\n  ".join(rows)
    return (f"const uint8_t {name}[] PROGMEM = {{\n  {body}\n}};\n"
            f"const size_t {name}_LEN = {len(data)};\n")


def main():
    app = APP.read_text(encoding="utf-8")
    # everything before the first <header> belongs in <head>
    split = app.index("<header")
    page = HEAD + app[:split] + "</head>\n<body>\n" + app[split:] + "</body>\n</html>\n"
    html_gz = gzip.compress(page.encode("utf-8"), compresslevel=9, mtime=0)
    icon = ICON.read_bytes()

    OUT.write_text(
        "// Phone app served by the screen. Generated by tools/web2header.py from\n"
        "// web/app.html and web/icon.png: edit those and run the script again.\n"
        "#pragma once\n#include <Arduino.h>\n\n"
        + c_array("WEBAPP_HTML_GZ", html_gz) + "\n"
        + c_array("WEBAPP_ICON_PNG", icon) + "\n"
        + 'const char WEBAPP_MANIFEST[] PROGMEM = R"json(' + json.dumps(MANIFEST) + ')json";\n',
        encoding="utf-8")
    print(f"{OUT.relative_to(ROOT)}: page {len(page)} bytes -> {len(html_gz)} gzipped, icon {len(icon)} bytes")


if __name__ == "__main__":
    main()
