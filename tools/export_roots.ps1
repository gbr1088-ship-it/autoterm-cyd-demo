# Writes src/github_roots.h: the root certificates the screens trust when they
# download updates from GitHub (gist.githubusercontent.com). GitHub has used
# Let's Encrypt, DigiCert and Sectigo (USERTrust); all are included so a change
# of provider doesn't break updates. Taken from this PC's trusted root store.
#
#   powershell -File tools\export_roots.ps1

$roots = 'ISRG Root X1', 'ISRG Root X2', 'DigiCert Global Root G2',
         'USERTrust RSA Certification Authority', 'USERTrust ECC Certification Authority'
$out = Join-Path $PSScriptRoot '..\src\github_roots.h'

$pem = foreach ($name in $roots) {
    $cert = Get-ChildItem Cert:\LocalMachine\Root, Cert:\CurrentUser\Root |
        Where-Object { ($_.Subject -split ',')[0] -eq "CN=$name" } |
        Sort-Object NotAfter -Descending | Select-Object -First 1
    if (-not $cert) { Write-Warning "not in this PC's store, skipped: $name"; continue }
    $b64 = [Convert]::ToBase64String($cert.RawData) -replace '(.{64})', "`$1`n"
    "// $name, expires $($cert.NotAfter.ToString('yyyy-MM-dd'))"
    "`"-----BEGIN CERTIFICATE-----\n`""
    foreach ($line in ($b64.Trim() -split "`n")) { "`"$line\n`"" }
    "`"-----END CERTIFICATE-----\n`""
}

$text = "#pragma once`n// Generated by tools/export_roots.ps1 - root certificates for update downloads`n" +
        "static const char GITHUB_ROOTS[] =`n" + ($pem -join "`n") + ";`n"
[IO.File]::WriteAllText((Resolve-Path (Split-Path $out)).Path + '\github_roots.h', $text, (New-Object Text.UTF8Encoding $false))
Write-Output "wrote $out"
